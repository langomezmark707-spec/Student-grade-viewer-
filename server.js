import express from 'express';
import path from 'path';
import fs from 'fs';
import { execSync } from 'child_process';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
// Render automatically provides process.env.PORT (defaults to 10000 on Render)
const PORT = process.env.PORT || 3000;

const distPath = path.join(__dirname, 'dist');
const indexPath = path.join(distPath, 'index.html');

// 🛠️ Automatic Build Guard:
// If Render ran 'start' without running 'npm run build' first, automatically compile dist now!
if (!fs.existsSync(indexPath)) {
  console.log('⚠️ dist/index.html not found! Running build automatically on Render...');
  try {
    const isBun = typeof process.versions.bun !== 'undefined' || fs.existsSync(path.join(__dirname, 'bun.lock'));
    const buildCmd = isBun ? 'bun run build' : 'npm run build';
    console.log(`Executing: ${buildCmd}`);
    execSync(buildCmd, { stdio: 'inherit', cwd: __dirname });
    console.log('✅ Auto-build completed successfully!');
  } catch (err) {
    console.error('❌ Build failed during startup:', err);
  }
}

// Serve static assets generated by Vite build
if (fs.existsSync(distPath)) {
  app.use(express.static(distPath));
}

// Health check endpoint for Render uptime monitoring
app.get('/healthz', (req, res) => {
  res.status(200).json({ status: 'healthy', uptime: process.uptime() });
});

// Catch-all route to serve index.html for Single Page Application (SPA) client-side routing
app.get('*', (req, res) => {
  if (fs.existsSync(indexPath)) {
    return res.sendFile(indexPath);
  }

  // Graceful fallback if build hasn't completed yet
  res.status(503).send(`
    <!doctype html>
    <html lang="en">
      <head>
        <meta charset="UTF-8" />
        <meta name="viewport" content="width=device-width, initial-scale=1.0" />
        <title>Initializing Application</title>
        <meta http-equiv="refresh" content="3" />
      </head>
      <body style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; display: grid; place-items: center; min-height: 100vh; background: #0f172a; color: #f8fafc; margin: 0;">
        <div style="text-align: center; padding: 2rem; max-width: 480px;">
          <div style="font-size: 2.5rem; margin-bottom: 1rem;">⚙️</div>
          <h2 style="font-size: 1.25rem; font-weight: bold; margin-bottom: 0.5rem;">Initializing Application on Render...</h2>
          <p style="color: #94a3b8; font-size: 0.875rem; line-height: 1.5;">The system is building the assets for first run. This page will reload automatically in a few seconds.</p>
        </div>
      </body>
    </html>
  `);
});

app.listen(PORT, '0.0.0.0', () => {
  console.log(`🚀 Production server running on http://0.0.0.0:${PORT}`);
});
